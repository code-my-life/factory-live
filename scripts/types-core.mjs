#!/usr/bin/env node
/**
 * The types of workflow-core's API, generated from the copies of its JSON Schema (ADR 0018, #57).
 *
 * The copies live in packages/contracts/src/workflow-core/schema/, with the commit of the core they come
 * from in source.json. From them, this script writes:
 * - generated/<name>.ts: the static types, by json-schema-to-typescript;
 * - generated/schemas.ts: the same schemas as values, from which z.fromJSONSchema builds the runtime checks.
 *
 *   npm run types:core                              regenerate from the copies
 *   npm run types:core -- --from ../workflow-core --ref origin/main
 *                                                   copy the schemas of that commit of the clone first (HEAD by default)
 *   npm run types:core -- --check                   exit 1, naming each file that differs, if regenerating would change one
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { compile } from 'json-schema-to-typescript';
import prettier from 'prettier';

const ROOT = resolve(import.meta.dirname, '..');
const DEFAULT_DIR = join(ROOT, 'packages', 'contracts', 'src', 'workflow-core');
/** The responses of the core that factory-live reads, by the name of their file in the core's schema/. */
export const SCHEMAS = [
  'workflows',
  'sheet-response',
  'items',
  'machine',
  'event',
  'error',
  'live',
  'activity',
  'usage',
  'interventions',
  'diagnosis',
  'run-verdicts',
  'declared-data',
  'agents',
];
const BANNER = (name) =>
  `/* Generated by npm run types:core from schema/${name}.schema.json of workflow-core: do not edit. */`;

function argument(name) {
  const at = process.argv.indexOf(name);
  return at === -1 ? null : (process.argv[at + 1] ?? null);
}

function copyFrom(clone, ref, dir) {
  const commit = execFileSync('git', ['-C', clone, 'rev-parse', `${ref}^{commit}`], {
    encoding: 'utf8',
  }).trim();
  mkdirSync(join(dir, 'schema'), { recursive: true });
  for (const name of SCHEMAS) {
    const text = execFileSync(
      'git',
      ['-C', clone, 'show', `${commit}:schema/${name}.schema.json`],
      {
        encoding: 'utf8',
      },
    );
    writeFileSync(join(dir, 'schema', `${name}.schema.json`), text);
  }
  const source = { repository: 'code-my-life/workflow-core', commit, schemas: SCHEMAS };
  writeFileSync(join(dir, 'source.json'), `${JSON.stringify(source, null, 2)}\n`);
}

const camel = (name) => name.replace(/-(\w)/g, (_, letter) => letter.toUpperCase());

/** Every generated file of `dir`, by its path, as this script writes it. */
export async function generate(dir) {
  const options = {
    ...(await prettier.resolveConfig(join(DEFAULT_DIR, 'generated', 'x.ts'))),
    parser: 'typescript',
  };
  const files = new Map();
  const values = [];
  for (const name of SCHEMAS) {
    const schema = JSON.parse(readFileSync(join(dir, 'schema', `${name}.schema.json`), 'utf8'));
    const types = await compile(schema, schema.title ?? name, {
      bannerComment: BANNER(name),
      format: false,
      additionalProperties: true,
      unreachableDefinitions: false,
    });
    files.set(join(dir, 'generated', `${name}.ts`), await prettier.format(types, options));
    values.push(`export const ${camel(name)}Schema: unknown = ${JSON.stringify(schema)};`);
  }
  const header =
    '/* Generated by npm run types:core from the schema/ copies of workflow-core: do not edit. */\n';
  files.set(
    join(dir, 'generated', 'schemas.ts'),
    await prettier.format(header + values.join('\n'), options),
  );
  return files;
}

async function main() {
  const dir = resolve(argument('--dir') ?? DEFAULT_DIR);
  const from = argument('--from');
  if (from) copyFrom(resolve(from), argument('--ref') ?? 'HEAD', dir);
  if (!existsSync(join(dir, 'schema'))) {
    console.error(`types:core : aucune copie des schémas dans ${dir}/schema`);
    return 1;
  }
  const files = await generate(dir);
  if (process.argv.includes('--check')) {
    const stale = [...files].filter(
      ([path, text]) => !existsSync(path) || readFileSync(path, 'utf8') !== text,
    );
    for (const [path] of stale)
      console.error(`types:core : ${path} n'est pas à jour (npm run types:core)`);
    const known = new Set([...files.keys()]);
    const extra = existsSync(join(dir, 'generated'))
      ? readdirSync(join(dir, 'generated')).filter(
          (name) => !known.has(join(dir, 'generated', name)),
        )
      : [];
    for (const name of extra)
      console.error(`types:core : generated/${name} ne vient d'aucun schéma`);
    return stale.length + extra.length === 0 ? 0 : 1;
  }
  mkdirSync(join(dir, 'generated'), { recursive: true });
  for (const [path, text] of files) writeFileSync(path, text);
  console.log(`types:core : ${files.size} fichiers écrits dans ${dir}/generated`);
  return 0;
}

process.exitCode = await main();
